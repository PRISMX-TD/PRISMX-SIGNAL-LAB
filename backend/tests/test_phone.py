"""手机号规范化：合法输入要留住，非法输入要挡掉，合法号码绝不能被改错。

第三条是最重要的：静默把一个有效号码改成另一个号码，比直接拒收严重得多——
用户以为留了联系方式，我们存了个打不通的号，而且没有任何人会发现。
"""
import pytest

from app.services.phone import compose_phone, normalize_phone


# ---------- 规范化：能接受的输入形态 ----------


@pytest.mark.parametrize("raw,expected", [
    ("+60123456789", "+60123456789"),          # 已经是 E.164
    ("+60 12-345 6789", "+60123456789"),       # 空格与连字符
    ("+60 (12) 345.6789", "+60123456789"),     # 括号与点
    ("  +60123456789  ", "+60123456789"),      # 首尾空白
    ("0060123456789", "+60123456789"),         # 国际拨号前缀 00
    ("01160123456789", "+60123456789"),        # 北美国际拨号前缀 011
    ("+8613800138000", "+8613800138000"),      # 中国
    ("+6591234567", "+6591234567"),            # 新加坡
    ("+14155552671", "+14155552671"),          # 美国
])
def test_accepts_and_normalises(raw, expected):
    assert normalize_phone(raw) == expected


# ---------- 规范化：必须挡掉的输入 ----------


@pytest.mark.parametrize("raw", [
    "",                       # 空
    "   ",                    # 纯空白
    "60123456789",            # 没有 +，无从判断区号，刻意不猜
    "+0123456789",            # 区号不能以 0 开头
    "+601",                   # 太短
    "+6012345678901234567",   # 超过 E.164 的 15 位上限
    "+60abc456789",           # 含字母
    "phone",                  # 完全不是号码
])
def test_rejects(raw):
    assert normalize_phone(raw) is None


def test_never_mangles_a_valid_number():
    """回归：曾经尝试在这里去「区号后的前导 0」，把 +60123456789 削成了 +6123456789。

    只拿到整串时无从知道区号在哪断开（"6" 后面正好是 0），任何猜法都会毁掉
    合法号码。分段是 compose_phone 的职责。
    """
    for n in ["+60123456789", "+6012345678", "+10234567890", "+440234567890"]:
        assert normalize_phone(n) == n


# ---------- 分段合成：知道区号才能安全去前导 0 ----------


@pytest.mark.parametrize("dial,national,expected", [
    ("60", "123456789", "+60123456789"),
    ("+60", "123456789", "+60123456789"),      # 区号带不带 + 都行
    ("60", "0123456789", "+60123456789"),      # 去掉本地拨号的前导 0
    ("60", "012-345 6789", "+60123456789"),    # 分隔符 + 前导 0
    ("86", "13800138000", "+8613800138000"),
    ("65", "91234567", "+6591234567"),
])
def test_compose(dial, national, expected):
    assert compose_phone(dial, national) == expected


@pytest.mark.parametrize("dial,national", [
    ("", "123456789"),        # 没区号
    ("60", ""),               # 没号码
    ("abc", "123456789"),     # 区号不是数字
    ("60", "abc"),            # 号码不是数字
    ("60", "00123456789"),    # 两个前导 0：只去一个，剩下的让校验挡掉
    ("60", "1"),              # 合成后太短
])
def test_compose_rejects(dial, national):
    assert compose_phone(dial, national) is None
