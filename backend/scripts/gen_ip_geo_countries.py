"""生成 app/services/ip_geo_countries.py：ISO alpha-2 → (中文名, 英文名, 数字码)。

一次性脚本，结果提交进仓库，运行时不依赖 pycountry。
台湾 / 香港 / 澳门只写名字（产品决定，2026-10-25），几个官方长名换成常用短名。
Generates the alpha-2 → (zh, en, numeric) table. TW/HK/MO are plain names by
product decision; a few long official names are replaced with common short ones.

用法 / usage:  python scripts/gen_ip_geo_countries.py > app/services/ip_geo_countries.py
"""
import gettext

import pycountry

OVERRIDES = {
    "TW": ("台湾", "Taiwan"),
    "HK": ("香港", "Hong Kong"),
    "MO": ("澳门", "Macao"),
    "KR": ("韩国", "South Korea"),
    "KP": ("朝鲜", "North Korea"),
    "VN": ("越南", "Vietnam"),
    "LA": ("老挝", "Laos"),
    "RU": ("俄罗斯", "Russia"),
    "IR": ("伊朗", "Iran"),
    "SY": ("叙利亚", "Syria"),
    "BO": ("玻利维亚", "Bolivia"),
    "VE": ("委内瑞拉", "Venezuela"),
    "TZ": ("坦桑尼亚", "Tanzania"),
    "MD": ("摩尔多瓦", "Moldova"),
    "PS": ("巴勒斯坦", "Palestine"),
    # pycountry zh_CN 目录里的错字 / 台湾译法，换成大陆通用写法（英文名不变）
    # misspelled or Taiwan-style names in the zh_CN catalog -> mainland standard (English unchanged)
    "KH": ("柬埔寨", "Cambodia"),
    "GT": ("危地马拉", "Guatemala"),
    "PF": ("法属波利尼西亚", "French Polynesia"),
    "KG": ("吉尔吉斯斯坦", "Kyrgyzstan"),
    "BD": ("孟加拉国", "Bangladesh"),
}


def main() -> None:
    zh = gettext.translation("iso3166-1", pycountry.LOCALES_DIR, languages=["zh_CN"])
    print('"""ISO 3166-1 alpha-2 → (中文名, 英文名, 数字码)。由 scripts/gen_ip_geo_countries.py 生成，勿手改。')
    print('Generated by scripts/gen_ip_geo_countries.py — do not edit by hand."""')
    print()
    print("COUNTRIES: dict[str, tuple[str, str, str]] = {")
    for c in sorted(pycountry.countries, key=lambda c: c.alpha_2):
        en = getattr(c, "common_name", None) or c.name
        name_zh = zh.gettext(c.name)
        if c.alpha_2 in OVERRIDES:
            name_zh, en = OVERRIDES[c.alpha_2]
        print(f"    {c.alpha_2!r}: ({name_zh!r}, {en!r}, {c.numeric!r}),")
    print("}")


if __name__ == "__main__":
    main()
