const MAX_PHRASE_TOKENS = 5

/** 指标 id 的中文名；有一段对不上就返回 null。/ Chinese name of a measure id, or null if any piece is unknown. */
export function measureZh(measure: string): string | null {
  const tokens = measure.toLowerCase().split('_').filter(Boolean)
  const base: string[] = []
  const tail: string[] = []
  let i = 0
  while (i < tokens.length) {
    let hit = 0
    for (let n = Math.min(MAX_PHRASE_TOKENS, tokens.length - i); n >= 1; n--) {
      const key = tokens.slice(i, i + n).join('_')
      if (PHRASES[key] !== undefined) {
        // 名字只能出现在后缀之前（cpi_yoy，不会是 yoy_cpi）/ names come before suffixes
        if (tail.length) return null
        base.push(PHRASES[key])
        hit = n
        break
      }
      if (SUFFIXES[key] !== undefined) {
        tail.push(SUFFIXES[key])
        hit = n
        break
      }
    }
    if (!hit) return null
    i += hit
  }
  if (!base.length) return null
  return [base.join(''), ...tail].join(' ')
}

