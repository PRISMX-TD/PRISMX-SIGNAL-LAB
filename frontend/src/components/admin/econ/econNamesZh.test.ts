describe('econNamesZh', () => {
  it('names every known measure in Chinese', () => {
    expect(MEASURES.filter((m) => !measureZh(m))).toEqual([])
  })
  it('names every known release in Chinese', () => {
    expect(RELEASE_NAMES.filter((n) => !releaseZh(n))).toEqual([])
  })
  it('composes phrases and suffixes', () => {
    expect(measureZh('core_pce_price_index_mom')).toBe('核心PCE物价指数 月率')
    expect(measureZh('retail_sales_ex_autos_mom')).toBe('零售销售（除汽车） 月率')
    expect(measureZh('fixed_asset_investment_ytd_yoy')).toBe('固定资产投资 年初至今 年率')
    expect(measureZh('initial_claims_4w_average')).toBe('初请失业金人数 四周均值')
    expect(measureZh('producer_price_ex_food_energy_trade_change_yoy')).toBe('PPI（除食品、能源和贸易） 年率')
    expect(measureZh('unemployment_rate')).toBe('失业率')
  })
  it('returns null instead of a half-translated name', () => {
    expect(measureZh('retail_sales_of_unicorns_mom')).toBeNull()
    expect(measureZh('yoy')).toBeNull()
    expect(releaseZh('Something new')).toBeNull()
  })
})
